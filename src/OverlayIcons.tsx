/// Small monochrome stroke icons for the Interview Mode overlay's header —
/// swapped in for emoji glyphs (🎙️🔈✥⛶⋮ etc.), which render as colorful,
/// inconsistently-sized platform emoji rather than the crisp thin-line icons
/// a toolbar like this needs. Hand-authored (no icon-library dependency) in
/// a consistent Lucide-style 24x24 stroke grid so they all read as one
/// family regardless of which one is used where.

import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Icon({ size = 14, children, ...rest }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...rest}
    >
      {children}
    </svg>
  );
}

