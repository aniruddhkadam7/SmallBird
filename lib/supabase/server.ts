// Server-side Supabase client (Server Components, Server Actions, route
// handlers, middleware) -- reads/writes the session via cookies. Still only
// the public anon key; server-side here means "runs on Vercel's server", not
// "trusted with the service-role key". Real authorization for every admin
// action is re-checked inside the admin-* Edge Functions regardless of
// anything this client reports.
import { createServerClient, type CookieOptions } from "@supabase/ssr";
import { cookies } from "next/headers";

export async function createClient() {
  const cookieStore = await cookies();

  return createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        get(name: string) {
          return cookieStore.get(name)?.value;
        },
        set(name: string, value: string, options: CookieOptions) {
          try {
            cookieStore.set({ name, value, ...options });
          } catch {
            // Called from a Server Component -- middleware refreshes the
            // session cookie instead, so this is safe to ignore.
          }
        },
        remove(name: string, options: CookieOptions) {
          try {
            cookieStore.set({ name, value: "", ...options });
          } catch {
            // Same as above.
          }
        },
      },
    },
  );
}
